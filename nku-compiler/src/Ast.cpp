class FunctionTracer {
public:
    explicit FunctionTracer(void* ptr)
        : m_ptr(ptr) {
        printIndent();
        std::cout << "Entering " << getClassName() << std::endl;
        indentLevel++;
    }

    ~FunctionTracer() {
        indentLevel--;
        printIndent();
        std::cout << "Exiting " << getClassName() << std::endl;
    }

private:
    void* m_ptr;
    static int indentLevel;
    void printIndent() const {
        for (int i = 0; i < indentLevel; ++i) {
            std::cout << "  ";  
        }
    }
    std::string getClassName() const {
        return typeid(*static_cast<Node*>(m_ptr)).name(); 
    }
};
