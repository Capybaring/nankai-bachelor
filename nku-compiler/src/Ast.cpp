void BinaryExpr::typeCheck(Node **recursive)
{
    // TODO: 实现二元表达式的类型检查逻辑

    expr1->typeCheck((Node **)&(this->expr1));
    if(expr2 != nullptr)
        expr2->typeCheck((Node **)&(this->expr2));
    else
        return;
    Type *expr1_type = expr1->getSymPtr()->getType();
    Type *expr2_type = expr2->getSymPtr()->getType();
    // bool isVoidType(const Type* expr_type) {
    // return expr_type->toStr() == "void()";
    // }

    if (expr1_type->toStr() == "void()") {
        fprintf(stderr, " empty type %s can not assignment!",
                expr1_type->toStr().c_str());
        exit(EXIT_FAILURE);
        return;
    }
    else{
        if(expr2_type->toStr() == "void()"){
        fprintf(stderr, " empty type %s can not assignment!",
                expr2_type->toStr().c_str());
        exit(EXIT_FAILURE);
        return;
        }
    }

    if (expr1->getSymPtr()->isConstant() && expr2->getSymPtr()->isConstant())
    {
        int value1 = dynamic_cast<ConstantSymbolEntry *>(expr1->getSymPtr())->getValue();
        int value2 = dynamic_cast<ConstantSymbolEntry *>(expr2->getSymPtr())->getValue();
        int result = 0;
        switch (op)
        {
        case ADD:
            result = value1 + value2;
            break;
        case SUB:
            result = value1 - value2;
            break;
        case MUL:
            result = value1 * value2;
            break;
        case DIV:
            result = value1 / value2;
            break;
        case MOD:
            result = value1 % value2;
            break;
        case AND:
            result = value1 && value2;
            break;
        case OR:
            result = value1 || value2;
            break;
        case LESS:
            result = value1 < value2;
            break;
        case GREATER:
            result = value1 > value2;
            break;
        case EQ:
            result = value1 == value2;
            break;
        case NEQ:
            result = value1 != value2;
            break;
        case GEQ:
            result = value1 >= value2;
            break;
        case LEQ:
            result = value1 <= value2;
            break;
        }
        SymbolEntry *se = new ConstantSymbolEntry(TypeSystem::intType, result);
        Constant *newNode = new Constant(se);
        *recursive = (Node *)newNode;
    }
}

